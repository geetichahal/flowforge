TIMEOUT = 30
REF = re.compile(r"\{\{\s*([A-Za-z_]\w*)((?:\.[\w-]+)*)\s*\}\}")


class ConfigError(Exception):
    """A required environment variable is missing."""


class StepFailed(Exception):
    """A workflow step raised an error; carries the step id and the original exception."""

    def __init__(self, step_id, error):
        super().__init__(step_id + ": " + type(error).__name__ + ": " + str(error))
        self.step_id = step_id
        self.error = error


def as_text(value):
    """Message bodies must be text: structured data (an API response, a list of rows) is sent as JSON."""
    return value if isinstance(value, str) else json.dumps(value, default=str)


def env(name):
    """Read configuration from the environment. Secrets never live in this file."""
    value = os.environ.get(name)
    if not value:
        if DRY_RUN:
            return "<" + name + ">"
        raise ConfigError("missing environment variable " + name)
    return value


def lookup(ctx, root, path):
    if root == "env":
        return env(path[0])
    value = ctx.get(root, {})
    for key in path:
        if isinstance(value, dict):
            value = value.get(key, "")
        elif isinstance(value, list) and key.isdigit() and int(key) < len(value):
            value = value[int(key)]
        else:
            return ""
    return value


def render(value, ctx):
    """Resolve {{step.field}} references. A value that is exactly one reference keeps its type."""
    if isinstance(value, dict):
        return {k: render(v, ctx) for k, v in value.items()}
    if isinstance(value, list):
        return [render(v, ctx) for v in value]
    if not isinstance(value, str):
        return value
    whole = REF.fullmatch(value.strip())
    if whole:
        return lookup(ctx, whole.group(1), [p for p in whole.group(2).split(".") if p])

    def one(m):
        v = lookup(ctx, m.group(1), [p for p in m.group(2).split(".") if p])
        return v if isinstance(v, str) else json.dumps(v) if isinstance(v, (dict, list)) else str(v)
    return REF.sub(one, value)


def approve(action):
    """Human approval gate for every real external action."""
    if DRY_RUN:
        print("  [dry-run] would " + action)
        return False
    if AUTO_APPROVE:
        return True
    answer = input("  Approve: " + action + "? [y/N] ").strip().lower()
    return answer in ("y", "yes")


def http(method, url, **kwargs):
    if requests is None:
        raise RuntimeError("Install requests to run for real: pip install requests")
    response = requests.request(method, url, timeout=TIMEOUT, **kwargs)
    response.raise_for_status()
    return response


def google_headers():
    # An OAuth access token with the needed Google scopes (Gmail/Drive/Sheets/Calendar).
    return {"Authorization": "Bearer " + env("GOOGLE_ACCESS_TOKEN")}


def check(left, operator, right):
    def num(x):
        try:
            return float(x)
        except (TypeError, ValueError):
            return None
    l, r = ("" if left is None else str(left)), ("" if right is None else str(right))
    if operator == "contains":
        return r.lower() in l.lower()
    if operator == "not_contains":
        return r.lower() not in l.lower()
    if operator == "equals":
        return l.strip().lower() == r.strip().lower()
    if operator == "not_equals":
        return l.strip().lower() != r.strip().lower()
    if operator == "starts_with":
        return l.lower().startswith(r.lower())
    if operator == "ends_with":
        return l.lower().endswith(r.lower())
    if operator in ("greater_than", "less_than"):
        a, b = num(l), num(r)
        if a is None or b is None:
            return False
        return a > b if operator == "greater_than" else a < b
    if operator == "is_empty":
        return l.strip() == ""
    if operator == "is_not_empty":
        return l.strip() != ""
    raise ValueError("unknown operator " + operator)


WEBHOOK_PATH = 'flowforge-hook'
WEBHOOK_METHOD = 'POST'
FORM_FIELDS = []
FORM_TITLE = ''
CRON = ''


# Step 1 of 4: Webhook (webhook)
# Start when an HTTP request is sent to the automation's webhook URL.
# Trigger: starts the workflow; its output is available to later steps as {{trigger.<field>}}.
# Produces: body, headers, query
def step_trigger(ctx):
    """Webhook: Start when an HTTP request is sent to the automation's webhook URL."""
    PARAMS = {'path': 'flowforge-hook', 'method': 'POST'}
    SAMPLE = {   'body': {   'name': 'Test Customer',
                    'email': 'customer@example.com',
                    'amount': 250,
                    'message': 'Interested in the premium plan',
                    'event': 'signup'},
        'headers': {'content-type': 'application/json'},
        'query': {}}
    p = render(PARAMS, ctx)
    # Normally the payload arrives via --serve or --payload; this is the sample request.
    return SAMPLE


# Step 2 of 4: If amount is over 100 (condition)
# Branch: follow the 'true' edge when the check passes, otherwise the 'false' edge.
# Runs after 'trigger'.
# Uses data: trigger.body.amount
# Produces: result
def step_check(ctx):
    """If amount is over 100: Branch: follow the 'true' edge when the check passes, otherwise the 'false' edge."""
    PARAMS = {'field': '{{trigger.body.amount}}', 'value': '100', 'operator': 'greater_than'}
    SAMPLE = {'result': True}
    p = render(PARAMS, ctx)
    result = check(p["field"], p["operator"], p.get("value", ""))
    print("  condition " + repr(p["field"])[:60] + " " + p["operator"] + " " + repr(p.get("value", "")) + " -> " + str(result))
    return {"result": result}


# Step 3 of 4: Slack Message (slack_message)
# Post a message to Slack through an incoming-webhook URL.
# Runs after 'check' (when its check is true).
# Uses data: env.SLACK_WEBHOOK_URL, trigger.body
# Produces: ok
def step_notify_slack(ctx):
    """Slack Message: Post a message to Slack through an incoming-webhook URL."""
    PARAMS = {   'webhook_url': '{{env.SLACK_WEBHOOK_URL}}',
        'text': 'Webhook received: {{trigger.body}}',
        'channel': ''}
    SAMPLE = {'ok': True}
    p = render(PARAMS, ctx)
    if not approve("post to Slack: " + repr(str(p["text"])[:80])):
        return SAMPLE
    http("POST", p["webhook_url"], json={"text": as_text(p["text"])})
    return {"ok": True}


# Step 4 of 4: Append to Google Sheet (sheets_append)
# Append one row to a Google Sheet.
# Runs after 'check' (when its check is false).
# Uses data: env.SHEET_ID, trigger.body.amount
# Produces: row, updated_range
def step_append_row(ctx):
    """Append to Google Sheet: Append one row to a Google Sheet."""
    PARAMS = {'spreadsheet_id': '{{env.SHEET_ID}}', 'range': 'Sheet1!A1', 'values': '{{trigger.body.amount}}'}
    SAMPLE = {'updated_range': 'Sheet1!A12:C12', 'row': ['a', 'b', 'c']}
    p = render(PARAMS, ctx)
    values = p["values"]
    row = ([v.strip() for v in values.split(",")] if isinstance(values, str)
           else list(values) if isinstance(values, (list, tuple)) else [values])
    if not approve("append row " + repr(row) + " to sheet " + str(p["spreadsheet_id"])):
        return {**SAMPLE, "row": row}
    url = ("https://sheets.googleapis.com/v4/spreadsheets/" + p["spreadsheet_id"] + "/values/"
           + p["range"] + ":append")
    res = http("POST", url, headers=google_headers(), params={"valueInputOption": "USER_ENTERED"},
               json={"values": [row]}).json()
    return {"updated_range": res.get("updates", {}).get("updatedRange", ""), "row": row}


STEPS = [
    ('trigger', step_trigger, []),
    ('check', step_check, [('trigger', None)]),
    ('notify_slack', step_notify_slack, [('check', 'true')]),
    ('append_row', step_append_row, [('check', 'false')]),
]


def serve(port):
    from http.server import BaseHTTPRequestHandler, HTTPServer
    from urllib.parse import parse_qs, urlparse

    class Handler(BaseHTTPRequestHandler):
        def _reply(self, code, body, ctype="application/json"):
            data = body.encode() if isinstance(body, str) else body
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.end_headers()
            self.wfile.write(data)

        def do_GET(self):
            if FORM_FIELDS:
                inputs = "".join('<p><label>' + f + '<br><input name="' + f + '"></label></p>' for f in FORM_FIELDS)
                return self._reply(200, "<h1>" + FORM_TITLE + '</h1><form method="post">' + inputs
                                   + '<button>Submit</button></form>', "text/html")
            self._reply(405, '{"error": "use ' + WEBHOOK_METHOD + '"}')

        def do_POST(self):
            url = urlparse(self.path)
            if WEBHOOK_PATH and url.path.strip("/") != WEBHOOK_PATH.strip("/"):
                return self._reply(404, '{"error": "unknown path"}')
            raw = self.rfile.read(int(self.headers.get("Content-Length") or 0)).decode() or "{}"
            if FORM_FIELDS:
                fields = {k: v[0] for k, v in parse_qs(raw).items()}
                trigger = {**{f: fields.get(f, "") for f in FORM_FIELDS},
                           "submitted_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
            else:
                try:
                    body = json.loads(raw)
                except ValueError:
                    body = {"raw": raw}
                trigger = {"body": body, "headers": dict(self.headers), "query": {k: v[0] for k, v in parse_qs(url.query).items()}}
            try:
                ctx = run(trigger)
            except StepFailed as exc:
                return self._reply(500, json.dumps({"ok": False, "failed_step": exc.step_id, "error": str(exc.error)}))
            self._reply(200, json.dumps({"ok": True, "steps": list(ctx)}, default=str))

    print("Listening on http://localhost:%d/%s" % (port, WEBHOOK_PATH or ""))
    HTTPServer(("127.0.0.1", port), Handler).serve_forever()


MESSAGE = ""


def run(trigger_output=None):
    """Execute the steps in order. A step runs when at least one incoming edge is live."""
    ctx = {}
    for step_id, fn, incoming in STEPS:
        if not incoming:
            ctx[step_id] = trigger_output if trigger_output is not None else fn(ctx)
            print("[" + step_id + "] trigger fired")
            continue
        live = any(src in ctx and (branch is None or bool(ctx[src].get("result")) == (branch == "true"))
                   for src, branch in incoming)
        if not live:
            print("[" + step_id + "] skipped (branch not taken)")
            continue
        print("[" + step_id + "] running")
        try:
            ctx[step_id] = fn(ctx)
        except Exception as exc:  # stop at the first failing step; later steps depend on its output
            print("[" + step_id + "] FAILED: " + type(exc).__name__ + ": " + str(exc), file=sys.stderr)
            raise StepFailed(step_id, exc) from exc
    return ctx


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--payload", help="JSON file used as the trigger output (skips the trigger)")
    parser.add_argument("--serve", action="store_true", help="for webhook/form triggers: listen for requests")
    parser.add_argument("--port", type=int, default=int(os.environ.get("PORT", "8765")))
    parser.add_argument("--chat", action="store_true", help="manual trigger: keep asking for messages until you type exit")
    parser.add_argument("message", nargs="*", help="manual trigger: the input text")
    args = parser.parse_args()
    global MESSAGE
    MESSAGE = " ".join(args.message)
    print("Mode: " + ("DRY RUN (set FLOWFORGE_DRY_RUN=0 to run for real)" if DRY_RUN else "LIVE"))
    if args.serve:
        serve(args.port)
        return
    if args.chat:
        while True:
            try:
                MESSAGE = input("you> ").strip()
            except EOFError:
                break
            if MESSAGE.lower() in ("exit", "quit", ""):
                break
            try:
                ctx = run()
            except StepFailed as exc:
                print("error> step " + exc.step_id + " failed: " + str(exc.error))
                continue
            last = list(ctx.values())[-1]
            print("bot> " + str(last.get("answer", last.get("message", json.dumps(last, default=str)))))
        return
    payload = None
    if args.payload:
        with open(args.payload) as fh:
            payload = json.load(fh)
    try:
        ctx = run(payload)
    except StepFailed as exc:
        sys.exit("Automation stopped: step '" + exc.step_id + "' failed (" + str(exc.error) + "). No later steps ran.")
    print(json.dumps(ctx, indent=2, default=str))


if __name__ == "__main__":
    main()
