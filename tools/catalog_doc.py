"""Write docs/NODE_CATALOG.md from the catalog, with the Flowise and n8n nodes each type ACTUALLY generates.

    .venv/bin/python tools/catalog_doc.py

For every node type a minimal plan is built (trigger -> node, or node -> notify for triggers), both
generators are run, and the emitted Flowise node names and n8n node types are read from the output.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from flowforge import catalog  # noqa: E402
from flowforge.generators import flowise, n8n  # noqa: E402
from flowforge.plan import normalize  # noqa: E402

DUMMY = {"secret": "{{env.TOKEN}}", "number": 1, "mapping": {"value": "{{trigger.input}}"}}


def params_for(nt) -> dict:
    out = {}
    for p in nt.params:
        if p.required:
            if p.default not in (None, ""):
                out[p.name] = p.default
            elif p.kind == "enum":
                out[p.name] = p.options[0]
            else:
                out[p.name] = DUMMY.get(p.kind, "{{trigger.input}}" if nt.kind != "trigger" else "x")
    if nt.type == "condition":
        out |= {"field": "{{trigger.input}}", "operator": "contains", "value": "x"}
    if nt.type == "send_email":
        out["to"] = "{{env.MY_EMAIL}}"
    if nt.type == "http_request":
        out["url"] = "https://api.example.com/x"
    if nt.type == "schedule":
        out["cron"] = "0 9 * * *"
    return out


def main() -> int:
    rows = []
    for nt in catalog.NODES:
        if nt.kind == "trigger":
            plan = {"name": "t", "nodes": [{"id": "trigger", "type": nt.type, "params": params_for(nt)},
                                           {"id": "n", "type": "notify", "params": {"message": "hi"}}],
                    "edges": [{"from": "trigger", "to": "n"}]}
            target = "trigger"
        else:
            plan = {"name": "t", "nodes": [{"id": "trigger", "type": "manual", "params": {"input": "go"}},
                                           {"id": "n", "type": nt.type, "params": params_for(nt)}],
                    "edges": [{"from": "trigger", "to": "n"}] + ([{"from": "n", "to": "m", "branch": "true"}] if nt.type == "condition" else [])}
            if nt.type == "condition":
                plan["nodes"].append({"id": "m", "type": "notify", "params": {"message": "yes"}})
            target = "n"
        plan = normalize(plan)
        scaffold = {"trigger"} if nt.kind != "trigger" else set()
        scaffold |= {"n"} if nt.kind == "trigger" else set()
        scaffold |= {"m"}
        try:
            fw = json.loads(flowise.generate(plan)["export"]["AgentFlowV2"][0]["flowData"])["nodes"]
            # FlowForge ids map to Flowise nodes in plan order; drop nodes that belong to the scaffold steps
            fw_names = []
            for n in fw:
                nm = n["data"]["name"]
                if nt.kind != "trigger" and nm == "startAgentflow":
                    continue
                if nm == "directReplyAgentflow" and nt.type != "notify":
                    continue
                tool = n["data"]["inputs"].get("toolAgentflowSelectedTool")
                fw_names.append(nm + (f" ({tool})" if tool else ""))
            fw_names = list(dict.fromkeys(fw_names)) or ["(none)"]
        except Exception as exc:
            fw_names = [f"error: {exc}"]
        try:
            wf = n8n.generate(plan)["workflow"]["nodes"]
            baseline = {"n8n-nodes-base.manualTrigger"} if nt.kind != "trigger" else set()
            keep = [w for w in wf if w["type"] not in baseline]
            # the scaffold notify is the last node (a Set node) for triggers/conditions
            if (nt.kind == "trigger" or nt.type == "condition") and keep and keep[-1]["type"] == "n8n-nodes-base.set":
                keep = keep[:-1]
            n8n_name = " + ".join(f"`{w['type']} v{w['typeVersion']}`" for w in keep) or "–"
        except Exception as exc:
            n8n_name = f"error: {exc}"
        req = ", ".join(f"`{p.name}`" for p in nt.params if p.required) or "–"
        opt = ", ".join(f"`{p.name}`" for p in nt.params if not p.required) or "–"
        rows.append(f"| `{nt.type}` | {nt.kind} | {nt.description} | {req} | {opt} | "
                    f"{nt.flowise}: {' + '.join(fw_names)} | {nt.n8n}: {n8n_name} |")
    md = ["# Node catalog", "", f"{len(catalog.NODES)} node types. Generated by `tools/catalog_doc.py` from "
          "`flowforge/catalog.py`: the Flowise and n8n columns show the nodes the generators actually emit "
          "for a minimal plan using that type.", "",
          "Mapping status: **direct** = native equivalent; **approximate** = built from a general node "
          "(e.g. HTTP call to an incoming webhook, an Agent with a tool, a Custom Function); **none** = no "
          "equivalent: the step is reported as `W_FLOWISE_UNSUPPORTED`, shown as a sticky note on the Flowise "
          "canvas, and still performed by the n8n and Python outputs.", "",
          "| Type | Kind | Description | Required params | Optional params | Flowise (AgentFlow v2) | n8n |",
          "|---|---|---|---|---|---|---|", *rows]
    out = ROOT / "docs/NODE_CATALOG.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
